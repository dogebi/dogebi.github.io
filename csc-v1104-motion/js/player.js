/*
 * player.js — runtime for a narrated motion-design video that plays in the browser.
 *
 * Model: everything on the stage is a pure function of the playhead `t` (seconds).
 *   - one paused GSAP master timeline, set to `t` every frame
 *   - onFrame(fn) hooks, called with `t` every frame (canvas, counters, procedural motion)
 *   - CSS/WAAPI animations inside the stage, paused and set to `t` every frame
 * While narration is playing, the audio element is the clock and visuals follow it,
 * so sync holds during real-time playback (and screen recording) and seeking works.
 *
 * Normally you do not edit this file. Author the video in js/scenes.js via Video.define().
 */
(function () {
  'use strict';

  const DATA = window.VIDEO_DATA || null;
  const params = new URLSearchParams(location.search);
  const stage = document.getElementById('stage');
  const W = Number(stage.dataset.width) || 1920;
  const H = Number(stage.dataset.height) || 1080;
  stage.style.width = W + 'px';
  stage.style.height = H + 'px';
  const lang = (DATA && DATA.lang) || document.documentElement.lang || 'ko';
  const TXT = {
    ko: { loading: '불러오는 중…', play: '재생', dropLabel: '프레임 드랍', normal: '보통', copied: '복사됨', copyFailed: '복사하지 못했어요',
          shotCopied: '스크린샷 명령 복사됨' },
    en: { loading: 'Loading…', play: 'Play', dropLabel: 'Frame drop', normal: 'normal', copied: 'Copied', copyFailed: 'Could not copy',
          shotCopied: 'Screenshot command copied' },
  }[lang.startsWith('ko') ? 'ko' : 'en'];

  // ---------- state ----------
  let builder = null;
  let tl = null;
  const frameFns = [];
  const canvases = [];
  let t = 0;
  let duration = 0;
  let playing = false;
  let audioStarting = false;
  let anchorT = 0;
  let anchorPerf = 0;
  let scale = 1;
  let rate = 1;             // playback speed (Shift+> / Shift+<) — a review tool only; R (restart, for recording) resets it to 1
  let booted = false;       // the scenes are built and the start position restored (resume): before that nothing renders or is saved
  let refit = false;        // the canvases were re-sized (which blanks them): the next frame tells onFrame to redraw everything
  const audioDur = DATA ? DATA.audioDuration : 0;
  const audio = new Audio();
  let audioOk = !!(DATA && DATA.audio);
  audio.preload = 'auto';
  audio.addEventListener('error', () => {
    audioOk = false;
    console.error('[video] narration failed to load:', DATA && DATA.audio);
  });
  audio.preservesPitch = true;
  if (audioOk) audio.src = DATA.audio;

  // Opening the page: a black screen with one loading bar, then the video plays at once (no start buttons). ?warm also
  // warms up first (paints the whole video once — the second half of the bar), ?watch warms up and turns the frame-drop
  // watch on. Automated browsers and renders (?render) never start playback themselves.
  const LIVE = navigator.webdriver !== true && !params.has('render');
  const WARM = LIVE && (params.has('warm') || params.has('watch'));
  const LOADMAX = WARM ? 0.5 : 1;   // the share of the bar that loading fills (the warm-up fills the rest)
  const now = () => performance.now() / 1000;
  const clamp = (v, a, b) => Math.min(b, Math.max(a, v));

  // ---------- resume where you left off · captions on by default (this browser only) ----------
  // A reload goes straight back to the last position and plays from there, and keeps the C toggle.
  // Automated browsers (snapshots, recording) never read or write it, so they keep the old defaults.
  const AUTO = navigator.webdriver === true;
  const POS_KEY = 'vp-pos:' + location.pathname, CAP_KEY = 'vp-captions:' + location.pathname;
  const store = {
    get(k) { if (AUTO) return null; try { return localStorage.getItem(k); } catch (_) { return null; } },
    set(k, v) { if (AUTO) return; try { localStorage.setItem(k, v); } catch (_) { /* storage blocked: just don't remember */ } },
  };
  let savedAt = -1e9;
  function savePos(force = false) {
    // not before boot has restored the saved position (a resize, F or a hidden tab during the build would store 0), and the
    // warm-up pass moves the playhead: never remember those positions
    if (!booted || window.__warming) return;
    const n = now();
    if (!force && n - savedAt < 1) return;
    savedAt = n;
    store.set(POS_KEY, t.toFixed(2));
  }
  addEventListener('pagehide', () => savePos(true));
  document.addEventListener('visibilitychange', () => { if (document.visibilityState === 'hidden') savePos(true); });

  // ---------- public authoring API ----------
  // ---------- frame-by-frame rendering (?render) ----------
  // A tool that films the video frame by frame (a headless browser: seek → wait → capture, nothing plays in real time)
  // opens index.html?render: the player's UI, warm-up, drop watch and saved position are off, and
  //   Video.renderReady   true once the scenes are built (body.vp-ready)
  //   Video.renderBusy()  true while something registered with busy(fn) is still drawing the current time (a demo that
  //                       draws asynchronously) — the tool waits, seeks to the same t again, then captures
  const busyFns = [];
  const Video = {
    define(fn) { builder = fn; },
    /** loading progress (0..1) for the bar on the loading screen — a long build in scenes.js can report its steps with it */
    progress(p) { ui.progress(clamp(p, 0, 1) * LOADMAX); },
    get time() { return t; },
    get duration() { return duration; },
    /** the review speed (Shift+> / Shift+<; 1 after R and always in renders) — footage follows it (media.js) */
    get rate() { return rate; },
    play: () => play(),
    pause: () => pause(),
    seek: (x) => seek(x),
    renderReady: false,
    renderBusy: () => busyFns.some((fn) => { try { return !!fn(); } catch (_) { return false; } }),
  };
  window.Video = Video;
  window.__video = Video; // handy in the console

  // phrase times (js/sync.js, written by scripts/sync.mjs from script.json "at"): the second, from the cue start, at which
  // each phrase the agent read off its take starts. Used only while it belongs to this take (same take id, same duration
  // — a new cut or take means sync.mjs again); any other phrase is estimated by its character position, and for a
  // recorded cue the player says so once (no code here decides where a word or a pause is).
  const SYNC = window.SYNC || {};
  const said = new Set();
  const sayOnce = (k, msg) => { if (!said.has(k)) { said.add(k); console.warn(msg); } };
  function makeCue(c) {
    const text = c.text || '';
    const weight = (s) => s.replace(/[\s.,!?·…"'“”‘’()\[\]-]/g, '').length;
    const total = Math.max(1, weight(text));
    const m = SYNC[c.id];
    const measured = !!(m && c.take && m.take === c.take && Math.abs(m.d - c.duration) < 0.01 && m.phrases && typeof m.phrases === 'object');
    return Object.freeze({
      ...c,
      measured,
      /** time at a fraction (0..1) of this cue's spoken duration */
      at: (f) => c.start + clamp(f, 0, 1) * c.duration,
      /** roughly when a phrase is spoken — its character position in the cue's text. For a moment that only has to follow
          the line (a scene change, a camera move, a panel entering while the line runs), never for one that must land on a
          spoken word (that is when(), with the phrase's time set from the take). It never asks for a set time */
      about(phrase, offset = 0) {
        const i = text.indexOf(phrase);
        if (i < 0) {
          console.warn(`[video] cue "${c.id}": phrase not found: "${phrase}"`);
          return c.start + offset;
        }
        return c.start + c.duration * (weight(text.slice(0, i)) / total) + offset;
      },
      /** the moment a phrase is spoken, for what must land on that word: the time the agent set from the take (script.json
          "at" → js/sync.js); without one, the character-position estimate, and the player says so once */
      when(phrase, offset = 0) {
        const i = text.indexOf(phrase);
        if (i < 0) {
          console.warn(`[video] cue "${c.id}": phrase not found: "${phrase}"`);
          return c.start + offset;
        }
        if (measured && Object.prototype.hasOwnProperty.call(m.phrases, phrase)) return c.start + m.phrases[phrase] + offset;
        if (m && !measured) sayOnce(c.id, `[video] cue "${c.id}": js/sync.js does not belong to this take — run scripts/sync.mjs (using the estimate)`);
        else if (c.take) sayOnce(c.id + '\u0000' + phrase, `[video] cue "${c.id}": no time set for "${phrase}" — read the take (wave.mjs --cue ${c.id}), set it in script.json "at", run sync.mjs (using the estimate)`);
        return c.start + c.duration * (weight(text.slice(0, i)) / total) + offset;
      },
    });
  }

  function buildContext() {
    const cueList = DATA.cues.map(makeCue);
    const byId = new Map(cueList.map((c) => [c.id, c]));
    tl = gsap.timeline({ paused: true });
    for (const c of cueList) {
      tl.addLabel(c.id, c.start);
      tl.addLabel(c.id + '_end', c.end);
    }
    return {
      tl,
      gsap,
      stage,
      W,
      H,
      data: DATA,
      cues: cueList,
      cue(id) {
        const c = byId.get(id);
        if (!c) throw new Error(`[video] unknown cue id "${id}". Known: ${[...byId.keys()].join(', ')}`);
        return c;
      },
      /** show `target` only between `from` and `to` (seconds). Uses visibility, so CSS animations keep running. */
      scene(target, from, to) {
        const el = typeof target === 'string' ? stage.querySelector(target) : target;
        if (!el) throw new Error(`[video] scene target not found: ${target}`);
        // visibility only: opacity belongs to the segment's own fades (autoAlpha here fought them, and a backward seek over the
        // hide-set could leave a scene hidden — user: 「다시 앞으로 이동해도 … 장면 안나오네」)
        gsap.set(el, { visibility: 'hidden' });
        tl.set(el, { visibility: 'visible' }, from);
        if (to != null) tl.set(el, { visibility: 'hidden' }, to);
        return el;
      },
      onFrame(fn) { frameFns.push(fn); },
      /** fn() → true while something still draws the current time asynchronously (a frame-by-frame render waits) */
      busy(fn) { busyFns.push(fn); },
      /** deterministic PRNG (mulberry32). Same seed → same sequence, every run. */
      rand(seed = 1) {
        let a = seed >>> 0;
        return () => {
          a = (a + 0x6d2b79f5) >>> 0;
          let r = Math.imul(a ^ (a >>> 15), 1 | a);
          r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r;
          return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
        };
      },
      /** size a <canvas> for crisp drawing in stage coordinates; returns its 2D context. max caps the pixel ratio (a heavy
       *  full-frame canvas on a high-density screen: 2 instead of up to 3 keeps it light; a render at 1920 is ratio 1 anyway) */
      fitCanvas(canvas, w = W, h = H, max = 3) {
        const entry = { canvas, w, h, max, ctx: canvas.getContext('2d') };
        canvases.push(entry);
        sizeCanvas(entry);
        return entry.ctx;
      },
    };
  }

  function sizeCanvas(e) {
    // a frame-by-frame render (?render, e.g. 4K at device pixel ratio 2) draws every canvas at the full ratio; the cap only
    // spares live playback
    const ratio = Math.min(params.has('render') ? 4 : e.max || 3, Math.max(1, scale * (window.devicePixelRatio || 1)));
    e.canvas.width = Math.round(e.w * ratio);
    e.canvas.height = Math.round(e.h * ratio);
    e.canvas.style.width = e.w + 'px';
    e.canvas.style.height = e.h + 'px';
    e.ctx.setTransform(ratio, 0, 0, ratio, 0, 0);
  }

  // ---------- layout ----------
  function fit() {
    scale = Math.min(innerWidth / W, innerHeight / H);
    stage.style.transform = `translate(-50%, -50%) scale(${scale})`;
    for (const e of canvases) sizeCanvas(e);
    if (canvases.length) refit = true;   // a re-sized canvas is blank: every onFrame gets redraw = true on the next frame
    if (booted) render();
  }

  // ---------- rendering ----------
  // ---------- frame counter (?fc, live viewing only): the video frame at t, small, bottom left of the window ----------
  // frame = floor(t × fps), fps 60 (?fc=30 counts at 30). Off unless asked for: a screen recording would film it.
  const FC_ON = params.has('fc'), FC_FPS = Math.max(1, Number(params.get('fc')) || 60);
  let fcEl = null, fcLast = '';
  function frameCounter() {
    if (!FC_ON || AUTO || params.has('render')) return;
    if (!fcEl) { fcEl = document.createElement('div'); fcEl.className = 'vp-fc'; document.body.appendChild(fcEl); }
    const s = String(Math.floor(t * FC_FPS + 1e-6));   // the number only, no padding
    if (s !== fcLast) { fcEl.textContent = s; fcLast = s; }
  }

  function render() {
    // never sit exactly on 0: GSAP skips zero-duration sets placed at 0 until the playhead moves past them
    tl.time(clamp(t, 1e-4, tl.duration()), false);
    // fn(t, redraw): redraw is true once after the canvases were re-sized (window resize, fullscreen) — code that skips
    // drawing while nothing changed (TypeFX groups, cached canvases) must draw then
    const redraw = refit;
    refit = false;
    for (const fn of frameFns) fn(t, redraw);
    frameCounter();
    savePos();
    const ms = t * 1000;
    const anims = document.getAnimations ? document.getAnimations() : [];
    for (const a of anims) {
      const target = a.effect && a.effect.target;
      if (!target || !stage.contains(target)) continue;
      if (a.playState !== 'paused') a.pause();
      a.currentTime = ms;
    }
    ui.update();
  }

  // ---------- clock ----------
  // ---------- frame-drop watch (?watch, live viewing only) ----------
  // While playing, the interval between two display frames is compared with the display's own steady interval (the
  // lower quartile of the last two seconds): an interval clearly longer than that means the display had to skip a frame,
  // and the whole window turns red for a second. Playback stops on the frame where it happened; when the red goes, it
  // simply goes on from there (no rewind). Pausing, playing or seeking by hand during the red second takes over. Right after play, a seek or a hidden tab nothing is judged. Every drop
  // is kept in window.__drops ({ t, ms, frames }) and logged to the console, so the places can be reported by time.
  const DW = { on: false, last: null, skip: 0, d: [], n: 0, red: 0, shown: false, el: null, lab: null, log: [], back: null, ours: false };
  function watchOn() {
    if (DW.on || AUTO || params.has('render')) return;
    DW.el = document.createElement('div'); DW.el.className = 'vp-drop';
    DW.lab = document.createElement('div'); DW.lab.className = 'vp-drop-label'; DW.el.appendChild(DW.lab);
    document.body.appendChild(DW.el);
    DW.on = true; window.__drops = DW.log;
  }
  const watchSkip = (ms = 500) => { DW.skip = performance.now() + ms; DW.last = null; };
  const clockText = (x) => { const m = Math.floor(x / 60); return m + ':' + (x - m * 60).toFixed(2).padStart(5, '0'); };
  function watchFrame() {
    if (!DW.on) return;
    const p = performance.now(), live = playing && !audioStarting && document.visibilityState === 'visible';
    if (!live) DW.last = null;
    else {
      if (DW.last != null && p >= DW.skip) {
        const dt = p - DW.last;
        if (dt < 1000) {
          const base = DW.d.length >= 30 ? DW.d.slice().sort((a, b) => a - b)[Math.floor(DW.d.length / 4)] : 1000 / 60;
          DW.d.push(dt); if (DW.d.length > 120) DW.d.shift();
          if (dt > base * 1.6 + 2) {
            const lost = Math.max(1, Math.round(dt / base) - 1);
            DW.n++; DW.red = p + 1000;
            DW.log.push({ t: +t.toFixed(2), ms: Math.round(dt), frames: lost });
            DW.lab.textContent = `${TXT.dropLabel} ${DW.n} · ${clockText(t)} · ${Math.round(dt)}ms`;
            console.warn(`[video] frame drop at ${clockText(t)}: ${Math.round(dt)} ms (≈ ${lost} frame${lost > 1 ? 's' : ''} skipped)`);
            DW.ours = true; pause(); DW.ours = false;      // hold on the frame where it happened
            DW.back = t;
          }
        }
      }
      DW.last = p;
    }
    const show = p < DW.red;
    if (show !== DW.shown) { DW.el.classList.toggle('vp-on', show); DW.shown = show; }
    // the red is gone: go on from where it stopped
    if (!show && DW.back != null) { DW.back = null; DW.ours = true; play(); DW.ours = false; }
  }

  function tick() {
    watchFrame();
    if (playing && !audioStarting) {
      let next = anchorT + (now() - anchorPerf) * rate;
      if (audioOk && next < audioDur && !audio.paused && !audio.seeking) {
        const drift = audio.currentTime - next;
        if (Math.abs(drift) > 0.25) { anchorT = audio.currentTime; anchorPerf = now(); next = anchorT; }
        else if (Math.abs(drift) > 0.015) { anchorT += drift * 0.1; next += drift * 0.1; }
      }
      if (next >= duration) {
        next = duration;
        playing = false;
        audio.pause();
        document.body.classList.remove('vp-playing');
        document.body.classList.add('vp-ended');
      }
      t = next;
      render();
    }
    requestAnimationFrame(tick);
  }

  async function play() {
    if (playing || audioStarting) return;
    if (!DW.ours) DW.back = null;
    watchSkip(700);
    if (t >= duration - 1e-3) t = 0;
    document.body.classList.remove('vp-ended');
    if (t < audioDur && audioOk) {
      audioStarting = true;
      audio.currentTime = t;
      try {
        await audio.play();
        anchorT = audio.currentTime;
      } catch (err) {
        if (err && err.name === 'NotAllowedError') {
          audioStarting = false;
          console.warn('[video] autoplay blocked; waiting for a click.');
          ui.showStart();
          return;
        }
        console.error('[video] narration cannot play; continuing silently.', err);
        anchorT = t;
      }
      audioStarting = false;
    } else {
      anchorT = t;
    }
    anchorPerf = now();
    playing = true;
    document.body.classList.add('vp-playing');
  }

  function pause() {
    if (!DW.ours) DW.back = null;
    playing = false;
    audio.pause();
    document.body.classList.remove('vp-playing');
    render();
  }

  function seek(x) {
    if (!DW.ours) DW.back = null;
    watchSkip();
    t = clamp(x, 0, duration);
    document.body.classList.toggle('vp-ended', t >= duration);
    if (playing) {
      anchorT = t;
      anchorPerf = now();
      if (t < audioDur && audioOk) {
        audio.currentTime = t;
        if (audio.paused) audio.play().catch(() => {});
      } else {
        audio.pause();
      }
    }
    render();
  }

  // ---------- UI (lives outside the stage, never recorded unless shown) ----------
  const ui = (() => {
    const el = (tag, cls, parent = document.body) => {
      const n = document.createElement(tag);
      if (cls) n.className = cls;
      parent.appendChild(n);
      return n;
    };
    // the loading screen: all black, one thin bar in the middle that fills as the video loads; when it is full the
    // screen fades out and the video plays (no buttons). Only if the browser refuses to start the sound without a click
    // does it come back — black, with a play mark in the middle (a click, Space or Enter starts it).
    const start = el('div', 'vp-start');
    const loadBar = el('div', 'vp-load', start);
    const loadFill = el('div', 'vp-load-fill', loadBar);
    const title = el('div', 'vp-start-title', start);   // status text for the tools (render.py reads it); shown only for an error
    const go = el('button', 'vp-go', start);
    go.setAttribute('aria-label', TXT.play);
    title.textContent = TXT.loading;
    let warmBusy = false;
    // the bar eases toward the progress it is given and never goes back
    let shownP = 0, targetP = 0, barRaf = 0;
    const drawBar = () => {
      barRaf = 0;
      shownP += (targetP - shownP) * 0.2;
      if (targetP - shownP < 0.002) shownP = targetP;
      loadFill.style.transform = `scaleX(${shownP.toFixed(4)})`;
      if (shownP < targetP) barRaf = requestAnimationFrame(drawBar);
    };
    start.addEventListener('click', () => { if (start.classList.contains('vp-blocked')) ui.startNow(); });

    const captions = el('div', 'vp-captions', stage);
    const measurer = el('span', 'vp-captions vp-measure', stage); // same font as captions, never shown
    // the debug bar is one row: the time in seconds (the unit render.py's --from / --to take) on the left, the timeline
    // beside it, and the current cue's id and line written inside the timeline
    const debug = el('div', 'vp-debug');
    const dbgTime = el('div', 'vp-debug-time', debug);
    const bar = el('div', 'vp-debug-bar', debug);
    const fill = el('div', 'vp-debug-fill', bar);
    const dbgInfo = el('div', 'vp-debug-info', bar);
    let showCaptions = params.has('captions') || (!AUTO && store.get(CAP_KEY) !== '0');
    let showDebug = params.has('debug');
    let lastSeg = null;
    let plan = null; // caption segments: [{ start, end, text }]
    let cursorTimer = 0;

    // ---- one-line captions ----
    // Each cue's text is cut into segments that fit on one line (measured with the real caption font),
    // preferring clause breaks (after , . ? ! …) and never splitting a word; neighbours that fit together
    // are merged back. Each segment is shown for its share of the spoken cue (by character weight).
    // script.json may give `captions: ["…", "…"]` per cue to choose the segments by hand.
    const weightOf = (s) => s.replace(/[\s.,!?·…"'“”‘’()[\]-]/g, '').length;
    const clauseEnd = /[,.!?…·:;、，。！？]["'”’)\]]*$/;
    // max caption box width: CSS var --caption-max on #stage (px or % of the stage), default 80%
    const maxBox = () => {
      const v = getComputedStyle(stage).getPropertyValue('--caption-max').trim();
      return v.endsWith('px') ? parseFloat(v) : v.endsWith('%') ? (W * parseFloat(v)) / 100 : W * 0.8;
    };
    function fits(text) {
      measurer.textContent = text;
      return measurer.offsetWidth <= maxBox();
    }
    function balanced(words, n) {
      const total = words.reduce((a, w) => a + w.length + 1, 0);
      const lines = [];
      let cur = [];
      let acc = 0;
      words.forEach((w, i) => {
        cur.push(w);
        acc += w.length + 1;
        const linesLeft = n - lines.length - 1;
        if (linesLeft > 0 && acc >= total / n && words.length - i - 1 >= linesLeft) {
          lines.push(cur.join(' '));
          cur = [];
          acc = 0;
        }
      });
      if (cur.length) lines.push(cur.join(' '));
      return lines;
    }
    function toLines(text) {
      text = String(text || '').replace(/\s+/g, ' ').trim();
      if (!text || fits(text)) return text ? [text] : [];
      const clauses = [];
      let cur = [];
      for (const w of text.split(' ')) {
        cur.push(w);
        if (clauseEnd.test(w)) { clauses.push(cur.join(' ')); cur = []; }
      }
      if (cur.length) clauses.push(cur.join(' '));
      const pieces = [];
      for (const cl of clauses) {
        if (fits(cl)) { pieces.push(cl); continue; }
        const words = cl.split(' ');
        measurer.textContent = cl;
        for (let n = Math.max(2, Math.ceil(measurer.offsetWidth / maxBox())); ; n++) {
          const lines = balanced(words, n);
          if (lines.every(fits) || n >= words.length) { pieces.push(...lines); break; }
        }
      }
      const out = [];
      for (const p of pieces) {
        if (out.length && fits(out[out.length - 1] + ' ' + p)) out[out.length - 1] += ' ' + p;
        else out.push(p);
      }
      return out;
    }
    function buildPlan() {
      plan = [];
      for (const c of DATA.cues) {
        const segs = Array.isArray(c.captions) && c.captions.length ? c.captions.flatMap(toLines) : toLines(c.text);
        const ws = segs.map((s) => Math.max(1, weightOf(s)));
        const total = ws.reduce((a, b) => a + b, 0) || 1;
        let acc = 0;
        segs.forEach((text, i) => {
          const start = c.start + (c.duration * acc) / total;
          acc += ws[i];
          plan.push({ start, end: i === segs.length - 1 ? c.end : c.start + (c.duration * acc) / total, text, cue: c.id });
        });
      }
    }

    function currentCue() {
      if (!DATA) return null;
      for (const c of DATA.cues) if (t >= c.start && t < c.end) return c;
      return null;
    }
    function fmt(s) {
      const m = Math.floor(s / 60);
      return `${m}:${(s - m * 60).toFixed(2).padStart(5, '0')}`;
    }

    bar.addEventListener('pointerdown', (e) => {
      const r = bar.getBoundingClientRect();
      seek(((e.clientX - r.left) / r.width) * duration);
    });
    // debug-mode scrubbing with the mouse while Shift is held (no click; without Shift the mouse moves freely and the
    // playhead stays), the same everywhere on the screen — the debug panel is not special
    // (user: 「debug ui영역에서 이동할때라고 해서 특별취급하지 말자」): relative to the horizontal movement, with a gain set by the pointer's
    // height (「하단에서 좌우로 이동할수록 촘촘하게 … 상단에서 … 크게 … 가장 큰 이동은 한픽셀에 영상의 10%」, then 「아래서 … 100배 촘촘하게」):
    //    bottom edge 1 px = 1/3000 s, top edge 1 px = 2 % of the video (was 10 %), exponential in between. A click on the bar still jumps there.
    const GAIN_MIN = 1 / 3000, gainMax = () => duration * 0.02;                // top: 1 px = 2 % (user: 「최상단은 2%수준으로」)
    const gainAt = (y) => { const u = clamp(1 - y / Math.max(1, innerHeight), 0, 1); return GAIN_MIN * Math.pow(gainMax() / GAIN_MIN, u); };
    let lastX = null, target = null, scrubRaf = 0;
    const flush = () => { scrubRaf = 0; if (target != null) seek(target); };
    document.addEventListener('pointermove', (e) => {
      if (!showDebug || !tl || ui.startVisible() || !e.shiftKey) { lastX = null; return; }   // only while Shift is held
      if (lastX == null) { lastX = e.clientX; return; }
      const dx = e.clientX - lastX; lastX = e.clientX;
      if (!dx) return;
      target = clamp((target != null ? target : t) + dx * gainAt(e.clientY), 0, duration);
      if (!scrubRaf) scrubRaf = requestAnimationFrame(flush);
    });
    document.addEventListener('pointerleave', () => { lastX = null; });
    addEventListener('blur', () => { lastX = null; });
    // a seek from elsewhere (keys, playback) must not be undone by a stale target — but not Shift itself: held for scrubbing,
    // it repeats keydown, and resetting then would drop the movement not yet applied
    const syncTarget = (e) => { if (e && e.key === 'Shift') return; target = null; };
    document.addEventListener('keydown', syncTarget, true);
    document.addEventListener('pointerdown', syncTarget, true);
    document.addEventListener('mousemove', () => {
      document.body.classList.add('vp-cursor');
      clearTimeout(cursorTimer);
      cursorTimer = setTimeout(() => document.body.classList.remove('vp-cursor'), 1500);
    });

    return {
      /** load the caption font's glyphs for every caption text, so width measurements are exact
          (web fonts split into unicode-range subsets load lazily otherwise) */
      async prepareCaptions() {
        if (!DATA || !document.fonts || !document.fonts.load) return;
        const cs = getComputedStyle(measurer);
        const text = DATA.cues.map((c) => `${c.text || ''} ${(c.captions || []).join(' ')}`).join(' ');
        try {
          await document.fonts.load(`${cs.fontStyle} ${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`, text);
        } catch (err) {
          console.warn('[video] caption font did not load', err);
        }
      },
      /** the loading bar: p in 0..1 (only ever moves forward) */
      progress(p) {
        targetP = Math.max(targetP, clamp(p, 0, 1));
        if (!barRaf) barRaf = requestAnimationFrame(drawBar);
      },
      /** resolves once the bar is drawn full */
      barFull() {
        this.progress(1);
        return new Promise((res) => { const chk = () => (shownP >= 1 ? res() : requestAnimationFrame(chk)); chk(); });
      },
      ready() {
        buildPlan(); // caption glyphs are loaded by now (prepareCaptions), so measurements are exact
        title.textContent = (DATA && DATA.title) || document.title;
        for (const c of DATA.cues) {
          const m = el('div', 'vp-debug-mark', bar);
          m.style.left = (c.start / duration) * 100 + '%';
          m.style.width = (c.duration / duration) * 100 + '%';
          m.title = `${c.id}: ${c.text}`;
        }
        this.update();
      },
      // ?warm / ?watch: warm up before the first play (the pass moves the playhead; it is put back)
      async warm() {
        if (warmBusy) return;
        warmBusy = true;
        const from = t;
        try { await warmup(); } finally { warmBusy = false; }
        t = from; render();
      },
      startNow() {
        if (warmBusy) return;
        start.classList.remove('vp-blocked');
        this.hideStart();
        play();
      },
      warming() { return warmBusy; },
      hideStart() { start.classList.add('vp-hidden'); },
      /** the browser refused to start the sound without a click: black again, a play mark in the middle */
      showStart() { start.classList.add('vp-blocked'); start.classList.remove('vp-hidden'); },   // Space / Enter / a click start it
      startVisible() { return !start.classList.contains('vp-hidden'); },
      blocked() { return start.classList.contains('vp-blocked'); },
      error(msg) {
        title.textContent = '⚠ ' + msg;
        title.classList.add('vp-error');
        loadBar.style.display = 'none';
      },
      toggleCaptions() { showCaptions = !showCaptions; store.set(CAP_KEY, showCaptions ? '1' : '0'); lastSeg = undefined; this.update(); },
      toggleDebug() { showDebug = !showDebug; this.update(); },
      /** "0:55.12 / 35:28.84 [op05b] 대사…" + two newlines — the line the S key copies (between cues: the cue just before) */
      cueLine() {
        const c = currentCue() || [...DATA.cues].reverse().find((q) => q.start <= t);
        return `${fmt(t)} / ${fmt(duration)} ${c ? `[${c.id}] ${c.text}` : ''}`.trimEnd() + '\n\n';
      },
      update() {
        const c = currentCue();
        const seg = showCaptions && plan ? plan.find((p) => t >= p.start && t < p.end) || null : null;
        captions.classList.toggle('vp-on', !!seg);
        if (seg !== lastSeg) {
          captions.textContent = seg ? seg.text : '';
          lastSeg = seg;
        }
        debug.classList.toggle('vp-on', showDebug);
        if (showDebug) {
          dbgTime.textContent = `${t.toFixed(2)} / ${duration.toFixed(2)}${lang.startsWith('ko') ? '초' : 's'}`;
          dbgInfo.textContent = c ? `[${c.id}] ${c.text}` : '';
          fill.style.width = (duration ? (t / duration) * 100 : 0) + '%';
        }
      },
    };
  })();

  // ---------- keyboard ----------
  // ---------- playback speed: 0.25–2x in 0.25 steps, then 2.5x and 3x (user: 「3배속까지 가능하게해줘」) ----------
  const RATES = [0.25, 0.5, 0.75, 1, 1.25, 1.5, 1.75, 2, 2.5, 3];
  const rateToast = document.createElement('div');
  rateToast.className = 'vp-rate';
  let rateToastTimer = 0;
  function toast(text, ms = 900) {
    if (!rateToast.isConnected) document.body.appendChild(rateToast);
    rateToast.textContent = text;
    rateToast.classList.add('vp-on');
    clearTimeout(rateToastTimer);
    rateToastTimer = setTimeout(() => rateToast.classList.remove('vp-on'), ms);
  }
  function setRate(r) {
    if (playing) { anchorT = t; anchorPerf = now(); }   // re-anchor so the clock doesn't jump
    rate = r;
    audio.defaultPlaybackRate = r;
    audio.playbackRate = r;
    toast(r === 1 ? `1x (${TXT.normal})` : r + 'x');
  }
  // S: copy the current time, cue id and line (for review notes); falls back to execCommand where the Clipboard API is refused
  async function copyText(text) {
    try { await navigator.clipboard.writeText(text); return true; } catch (_) { /* fall back */ }
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.cssText = 'position:fixed;left:-9999px;top:0;opacity:0';
    document.body.appendChild(ta);
    ta.select();
    let ok = false;
    try { ok = document.execCommand('copy'); } catch (_) { ok = false; }
    ta.remove();
    return ok;
  }
  function stepRate(dir) {
    const i = RATES.indexOf(rate);
    setRate(RATES[clamp(i + dir, 0, RATES.length - 1)]);
  }

  function fullscreen() {
    if (document.fullscreenElement) document.exitFullscreen();
    else document.documentElement.requestFullscreen().catch(() => {});
  }
  document.addEventListener('keydown', (e) => {
    if (e.metaKey || e.ctrlKey || e.altKey) return;
    const k = e.key;
    // letter keys by their physical position (e.code), so they also work with the Korean input on (key = 'ㅇ' / 'Process')
    const is = (code, ...keys) => e.code === code || keys.includes(k);
    if (ui.startVisible()) {   // loading (or waiting for the click the browser asks for before sound)
      if (k === ' ' || k === 'Enter') { e.preventDefault(); if (tl && ui.blocked()) ui.startNow(); }
      else if (is('KeyF', 'f', 'F')) fullscreen();   // fullscreen before the video starts (when recording)
      return;
    }
    if (!tl) return;
    const step = e.shiftKey ? 5 : 0.5;
    if (e.shiftKey && (k === '>' || e.code === 'Period')) { e.preventDefault(); stepRate(+1); }
    else if (e.shiftKey && (k === '<' || e.code === 'Comma')) { e.preventDefault(); stepRate(-1); }
    else if (k === ' ') { e.preventDefault(); playing ? pause() : play(); }
    else if (k === 'ArrowRight') seek(t + step);
    else if (k === 'ArrowLeft') seek(t - step);
    else if (!e.shiftKey && is('Period', '.')) { if (!playing) seek(t + 1 / 30); }
    else if (!e.shiftKey && is('Comma', ',')) { if (!playing) seek(t - 1 / 30); }
    else if (k === 'Home' || is('Digit0', '0')) seek(0);
    // R starts a recording: always from the top at 1× (the speed keys are for review only)
    else if (is('KeyR', 'r', 'R')) { if (rate !== 1) setRate(1); seek(0); play(); }
    else if (is('KeyF', 'f', 'F')) fullscreen();
    else if (is('KeyC', 'c', 'C')) ui.toggleCaptions();
    else if (is('KeyS', 's', 'S')) {
      const line = ui.cueLine();
      copyText(line).then((ok) => toast(ok ? TXT.copied + ' · ' + line.split(' [')[0].split(' / ')[0] : TXT.copyFailed, 1200));
    }
    else if (is('KeyA', 'a', 'A')) {
      // A: the render.py contact-sheet command for this moment — 1 s either side, every 10th frame; pasted after
      // `python3 render.py ` in the project folder, so no project name (references/render.md)
      const from = Math.max(0, t - 1), to = Math.min(duration, t + 1);
      // + a short note in parentheses for whoever it is pasted to (an agent); in a terminal, paste up to the parenthesis
      const cmd = `--screenshot --from ${from.toFixed(2)} --to ${to.toFixed(2)} --gapframe 10 --fast --jobs 1 (check it with render.py from the script-to-motion skill)`;
      copyText(cmd).then((ok) => toast(ok ? TXT.shotCopied + ' · ' + clockText(from) + '–' + clockText(to) : TXT.copyFailed, 1400));
    }
    else if (is('KeyD', 'd', 'D')) ui.toggleDebug();
  });

  // ---------- boot ----------
  async function boot() {
    // the position to resume from, read before anything can overwrite it
    const saved = params.has('t') ? NaN : parseFloat(store.get(POS_KEY));
    const resume = Number.isFinite(saved);
    fit();
    addEventListener('resize', fit);
    document.addEventListener('fullscreenchange', fit);

    if (!DATA) return ui.error('js/cues.js is missing — run scripts/tts.mjs first.');
    if (typeof gsap === 'undefined') return ui.error('GSAP failed to load (vendor/gsap/gsap.min.js).');
    const plugins = ['SplitText', 'CustomEase', 'CustomBounce', 'CustomWiggle', 'DrawSVGPlugin',
      'MorphSVGPlugin', 'MotionPathPlugin', 'TextPlugin', 'ScrambleTextPlugin'];
    gsap.registerPlugin(...plugins.map((p) => window[p]).filter(Boolean));

    Video.progress(0.04);
    // Fonts must be ready before anything measures text (SplitText, layout-dependent tweens).
    const waitAudio = new Promise((res) => {
      if (!audioOk || audio.readyState >= 3) return res();
      audio.addEventListener('canplaythrough', res, { once: true });
      audio.addEventListener('error', res, { once: true });
      setTimeout(res, 5000);
    });
    await Promise.all([document.fonts ? document.fonts.ready : null, waitAudio]);
    Video.progress(0.2);   // scenes.js may take it from here with Video.progress(p) (a long build, many demos)

    if (!builder) return ui.error('js/scenes.js did not call Video.define().');
    try {
      await builder(buildContext());
    } catch (err) {
      console.error(err);
      return ui.error('scenes.js error: ' + (err && err.message ? err.message : err));
    }
    duration = Math.max(DATA.duration || 0, tl.duration());
    await ui.prepareCaptions();
    Video.progress(0.97);
    t = clamp(params.has('t') ? Number(params.get('t')) || 0 : resume ? saved : 0, 0, duration);
    booted = true;
    render();
    ui.ready();
    if (params.has('render')) document.body.classList.add('vp-render');
    Video.renderReady = true;
    document.body.classList.add('vp-ready');
    requestAnimationFrame(tick);
    // the tools (automated browsers, ?render) seek on their own: the screen just goes away
    if (!LIVE) { ui.hideStart(); return; }
    if (WARM) await ui.warm();
    await ui.barFull();
    if (params.has('watch')) watchOn();
    ui.startNow();   // straight into playback (from a saved position, where the last viewing stopped)
  }

  // ---------- warm-up (live viewing only; with ?warm or ?watch, on the second half of the loading bar) ----------
  // The first time a scene is shown the browser lays it out, rasterises its layers, decodes its images, compiles shaders
  // and optimises the code that draws it; doing that during playback drops frames on a slow computer (a second viewing is
  // smooth). So before the first play: decode the images, run the video's own warm-up hooks (window.__warmHooks — e.g.
  // demos that must wait for a WebGL slot: set up once, drawn, released, so their shaders are in the browser's cache),
  // then paint the whole timeline once, one frame per second of video, with the demos frozen (window.__warming).
  // Skipped in renders (?render), in headless checks and with ?nowarm. The picture is never affected: after the pass the
  // playhead goes back to where it starts.
  async function warmup() {
    if (AUTO || params.has('render') || params.has('nowarm')) return;
    const say = (p) => ui.progress(LOADMAX + (1 - LOADMAX) * clamp(p, 0, 1));
    const paint = () => new Promise((r) => requestAnimationFrame(() => r()));
    window.__warming = true;
    try {
      say(0);
      await Promise.all([...stage.querySelectorAll('img')].map((im) => (im.decode ? im.decode().catch(() => {}) : null)));
      const hooks = window.__warmHooks || [];
      for (let i = 0; i < hooks.length; i++) {
        try { await hooks[i]((p) => say(0.02 + 0.3 * (i + clamp(p, 0, 1)) / hooks.length)); } catch (err) { console.error('[warm-up]', err); }
      }
      for (let x = 0, n = 0; x <= duration; x += 1, n++) {
        t = x; render();
        if (n % 2 === 0) await paint();            // a painted frame: layout, raster and decoding happen now
        if (n % 10 === 0) say(0.32 + 0.68 * x / duration);
      }
    } finally {
      window.__warming = false;
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else setTimeout(boot, 0); // let scenes.js (loaded after this file) call Video.define first
})();
